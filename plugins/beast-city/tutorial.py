def get_tutorial_page(page_num):
    page = TUTORIAL_PAGES.get(page_num)
    if not page:
        available = "、".join(str(k) for k in sorted(TUTORIAL_PAGES.keys()))
        return f"第{page_num}页不存在。页码: {available}"
    return page["content"]


def get_tutorial_index():
    lines = ["教程目录\n══════════"]
    for num in sorted(TUTORIAL_PAGES.keys()):
        p = TUTORIAL_PAGES[num]
        lines.append(f"  {num}. {p['title']}")
    lines.append("\n「异兽教程 N」查看。例: 异兽教程 1")
    return "\n".join(lines)
